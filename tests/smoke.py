"""End-to-end demo checks. Start npm run dev first; uses system Chromium."""
import os
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE_URL = os.environ.get('ROMEO_TEST_URL', 'http://127.0.0.1:5173')
ARTIFACTS = Path(os.environ.get('ROMEO_TEST_ARTIFACTS', '/tmp/romeo-demo-checks'))
ARTIFACTS.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 1440, 'height': 1000}, accept_downloads=True)
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE_URL, wait_until='networkidle')
    expect(page.get_by_role('heading', name='Обзор сети', exact=True)).to_be_visible()
    initial_revenue = page.locator('.metric-value').first.inner_text()
    page.get_by_label('Магазин', exact=True).select_option('s1')
    assert page.locator('.metric-value').first.inner_text() != initial_revenue
    assert page.locator('.store-table tbody tr').count() == 1
    page.get_by_label('Период', exact=True).select_option('week')
    expect(page.locator('.chart-card .badge')).to_have_text('25–31 октября')
    page.get_by_label('Магазин', exact=True).select_option('all')
    page.get_by_label('Период', exact=True).select_option('month')
    page.screenshot(path=str(ARTIFACTS / 'overview-desktop.png'), full_page=True)
    print('PASS: dashboard filters and charts')

    with page.expect_download() as download:
        page.get_by_role('button', name='Скачать отчёт CSV').click()
    exported = download.value
    exported.save_as(str(ARTIFACTS / exported.suggested_filename))
    assert 'ДЕМО-ДАННЫЕ' in Path(exported.path()).read_text(encoding='utf-8-sig')
    print('PASS: CSV export')

    page.get_by_role('button', name='Финансы', exact=True).click()
    page.get_by_role('button', name='Движение денег', exact=True).click()
    page.get_by_label('Поиск операций').fill('Аренда')
    expect(page.locator('.operations-table tbody tr')).to_have_count(8)
    page.locator('.operation-name').first.click()
    expect(page.get_by_role('dialog')).to_contain_text('Банковская выписка · демо')
    page.get_by_role('button', name='Закрыть окно').click()
    page.get_by_label('Поиск операций').fill('нет-такой-операции')
    expect(page.get_by_text('Операции не найдены', exact=True)).to_be_visible()
    page.get_by_label('Поиск операций').fill('')
    page.get_by_role('button', name='Далее', exact=True).click()
    expect(page.locator('.pagination')).to_contain_text('11–20')
    print('PASS: cash operations, search, pagination and source details')

    page.get_by_role('button', name='Заявка на расход', exact=True).click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_label('Название расхода').fill('Демо: проверка холодильника')
    dialog.get_by_label('Сумма, ₸').fill('42000')
    dialog.get_by_label('Магазин').select_option('s1')
    dialog.get_by_label('Обоснование').fill('Проверить работу оборудования перед праздниками.')
    dialog.get_by_role('button', name='Отправить на согласование').click()
    page.get_by_role('button', name=re.compile('Демо: проверка холодильника')).click()
    page.get_by_role('button', name='Согласовать расход', exact=True).click()
    row = page.locator('.requests-table tbody tr').filter(has_text='Демо: проверка холодильника')
    expect(row).to_contain_text('Согласовано')
    page.reload(wait_until='networkidle')
    page.get_by_role('button', name='Финансы', exact=True).click()
    page.get_by_role('button', name=re.compile('^Заявки на расходы')).click()
    expect(page.locator('.requests-table tbody tr').filter(has_text='Демо: проверка холодильника')).to_contain_text('Согласовано')
    print('PASS: request creation, approval and persistence after reload')

    page.get_by_role('button', name=re.compile('^Задачи')).click()
    page.get_by_role('button', name='Новая задача', exact=True).click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_label('Название задачи').fill('Проверка демо-задачи')
    dialog.get_by_label('Ожидаемый результат').fill('Все позиции пересчитаны.')
    dialog.get_by_label('Магазин').select_option('s1')
    dialog.get_by_label('Ответственный').select_option(label='Меруерт')
    dialog.get_by_role('button', name='Создать задачу').click()
    card = page.locator('.task-card').filter(has_text='Проверка демо-задачи')
    card.get_by_role('button', name='Взять в работу').click()
    expect(page.locator('.kanban-column.doing')).to_contain_text('Проверка демо-задачи')
    card.get_by_role('button', name='Завершить задачу').click()
    expect(page.locator('.kanban-column.done')).to_contain_text('Проверка демо-задачи')
    print('PASS: task creation and completion')

    page.get_by_role('button', name=re.compile('^ИИ-помощник')).click()
    page.get_by_role('button', name='Какая выручка за октябрь?', exact=True).click()
    expect(page.locator('.answer-text')).to_contain_text('Выручка:')
    expect(page.locator('.answer-source')).to_contain_text('Октябрь 2026')
    page.screenshot(path=str(ARTIFACTS / 'assistant-desktop.png'), full_page=True)
    page.get_by_role('button', name='Сменить роль', exact=True).click()
    page.get_by_role('dialog').get_by_role('button', name=re.compile('Управляющий')).click()
    expect(page.get_by_role('heading', name='Ваш магазин в цифрах')).to_be_visible()
    assert page.get_by_label('Магазин', exact=True).locator('option').count() == 1
    page.get_by_role('button', name='Финансы', exact=True).click()
    page.get_by_role('button', name=re.compile('^Заявки на расходы')).click()
    assert 'Самал' not in page.locator('.requests-table').inner_text()
    page.get_by_role('button', name=re.compile('Упаковка для новой коллекции')).click()
    expect(page.get_by_role('button', name='Согласовать расход', exact=True)).to_have_count(0)
    page.keyboard.press('Escape')
    page.get_by_role('button', name=re.compile('^ИИ-помощник')).click()
    page.get_by_label('Вопрос помощнику').fill('Какая прибыль в Алматы?')
    page.get_by_role('button', name='Отправить вопрос').click()
    expect(page.locator('.answer-text')).to_contain_text('только данные магазина')
    print('PASS: assistant calculations, source attribution and manager restrictions')

    page.get_by_role('button', name='Сменить роль', exact=True).click()
    page.get_by_role('dialog').get_by_role('button', name=re.compile('Сотрудник')).click()
    expect(page.get_by_role('heading', name='Мои задачи')).to_be_visible()
    expect(page.locator('nav').get_by_role('button', name='Финансы', exact=True)).to_have_count(0)
    assert 'Самал' not in page.locator('main').inner_text()
    page.get_by_role('button', name=re.compile('^ИИ-помощник')).click()
    expect(page.locator('.answer-text')).to_have_count(0)
    page.get_by_label('Вопрос помощнику').fill('Покажи выручку всей сети')
    page.get_by_role('button', name='Отправить вопрос').click()
    expect(page.locator('.answer-text')).to_contain_text('В роли сотрудника')
    page.get_by_label('Вопрос помощнику').fill('Как оформить списание?')
    page.get_by_role('button', name='Отправить вопрос').click()
    expect(page.locator('.answer-text').last).to_contain_text('Проверьте фактическое количество')
    print('PASS: employee restrictions, cleared chat on role change and instructions')

    page.get_by_role('button', name='Сменить роль', exact=True).click()
    page.get_by_role('dialog').get_by_role('button', name=re.compile('Финансист')).click()
    page.get_by_label('Поиск по системе').fill('Самал')
    page.locator('.search-results').get_by_role('button').click()
    expect(page.get_by_role('dialog')).to_contain_text('Самал')
    page.keyboard.press('Escape')
    page.get_by_role('button', name='Уведомления', exact=True).click()
    expect(page.locator('.notification-popover')).to_contain_text('Сервис холодильной камеры')
    page.keyboard.press('Escape')
    page.get_by_role('button', name='Настройки', exact=True).click()
    page.get_by_role('button', name='Сбросить демо', exact=True).click()
    page.get_by_role('button', name='Восстановить демо', exact=True).click()
    assert len(page.evaluate('JSON.parse(localStorage.getItem("romeo-demo-v1-requests"))')) == 4
    print('PASS: financier role, global search, notifications and reset')

    mobile = context.new_page()
    mobile.set_viewport_size({'width': 390, 'height': 844})
    mobile.on('pageerror', lambda error: errors.append(str(error)))
    mobile.goto(BASE_URL, wait_until='networkidle')
    assert not mobile.evaluate('document.documentElement.scrollWidth > innerWidth'), 'Mobile page overflows'
    mobile.screenshot(path=str(ARTIFACTS / 'overview-mobile.png'), full_page=True)
    mobile.get_by_role('button', name='Открыть меню').click()
    mobile.get_by_role('button', name='Финансы', exact=True).click()
    expect(mobile.get_by_role('heading', name='Финансы', exact=True)).to_be_visible()
    assert not mobile.evaluate('document.documentElement.scrollWidth > innerWidth'), 'Mobile finance overflows'
    mobile.get_by_role('button', name='Заявка на расход', exact=True).click()
    expect(mobile.get_by_role('dialog')).to_be_visible()
    mobile.keyboard.press('Escape')
    print('PASS: mobile layout, navigation and form')
    assert not errors, errors
    print('PASS: no JavaScript page errors')
    browser.close()
