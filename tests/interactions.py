"""Exercise reference layout, settings, demo connections and secondary actions."""
import os
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

URL = os.environ.get('ROMEO_TEST_URL', 'http://127.0.0.1:5173')
OUT = Path(os.environ.get('ROMEO_TEST_ARTIFACTS', '/tmp/romeo-interaction-checks'))
OUT.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1290, 'height': 800}, accept_downloads=True)
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.emulate_media(reduced_motion='reduce')
    page.goto(URL, wait_until='networkidle')
    page.get_by_role('button', name=re.compile('^Быстрый старт')).click()
    expect(page.get_by_role('dialog')).to_contain_text('Добро пожаловать')
    page.get_by_role('button', name='Начать знакомство', exact=True).click()
    expect(page.get_by_role('dialog')).to_have_count(0)
    print('PASS: quick-start walkthrough')

    nav = page.locator('.sidebar')
    for name in ['Финансы', 'Магазины', 'Задачи', 'ИИ-помощник', 'Настройки', 'Обзор сети']:
        nav.get_by_role('button', name=re.compile('^' + re.escape(name))).click()
        expect(nav.get_by_role('button', name=re.compile('^' + re.escape(name)))).to_have_attribute('aria-current', 'page')
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), name
    page.screenshot(path=str(OUT / 'overview-reference.png'), full_page=True)
    print('PASS: all main navigation buttons and desktop layout')

    page.get_by_role('button', name='Настройки пространства', exact=True).click()
    expect(page.get_by_role('heading', name='Настройки пространства', exact=True)).to_be_visible()
    page.screenshot(path=str(OUT / 'settings-reference.png'), full_page=True)
    page.get_by_role('button', name='Выбрать аватар', exact=True).click()
    page.get_by_role('dialog').get_by_role('button', name='Цветок', exact=True).click()
    page.get_by_label('Название компании', exact=True).fill('Romeo · demo team')
    page.get_by_role('switch', name='Уведомления о расходах', exact=True).click()
    page.get_by_role('switch', name='Быстрый старт', exact=True).click()
    page.get_by_label('Часовой пояс', exact=True).select_option('UTC')
    page.get_by_role('button', name='Сохранить настройки', exact=True).click()
    expect(page.locator('.workspace-switch')).to_contain_text('Romeo · demo team')
    expect(page.locator('.workspace-flower svg')).to_have_count(1)
    expect(page.locator('.quick-start')).to_have_count(0)
    page.get_by_role('button', name='Уведомления', exact=True).click()
    expect(page.locator('.notification-popover')).to_contain_text('Уведомления отключены')
    page.locator('.notification-popover').get_by_role('button', name='Открыть настройки').click()
    page.reload(wait_until='networkidle')
    expect(page.locator('.workspace-switch')).to_contain_text('Romeo · demo team')
    page.get_by_role('button', name='Настройки пространства', exact=True).click()
    expect(page.get_by_label('Часовой пояс', exact=True)).to_have_value('UTC')
    expect(page.get_by_role('switch', name='Быстрый старт')).to_have_attribute('aria-checked', 'false')
    print('PASS: avatar, company name, notification and quick-start switches, timezone, save and persistence')

    page.get_by_role('tab', name='Интеграции', exact=True).click()
    page.get_by_role('button', name='Подключить Ботанический', exact=True).click()
    page.get_by_role('button', name='Запустить демо-подключение', exact=True).click()
    expect(page.get_by_role('button', name='Синхронизация…', exact=True)).to_be_disabled()
    expect(page.locator('.sync-result')).to_contain_text('Синхронизация завершена')
    expect(page.locator('.sync-result')).to_contain_text('92 дней продаж')
    page.get_by_role('button', name='Готово', exact=True).click()
    row = page.locator('.integration-item').filter(has_text='Ботанический')
    expect(row).to_contain_text('Подключено · демо')
    page.get_by_role('button', name='Обновить Ботанический', exact=True).click()
    page.get_by_role('button', name='Обновить демо-данные', exact=True).click()
    expect(page.locator('.sync-result')).to_contain_text('Синхронизация завершена')
    page.get_by_role('button', name='Готово', exact=True).click()
    page.reload(wait_until='networkidle')
    page.get_by_role('button', name='Настройки пространства', exact=True).click()
    page.get_by_role('tab', name='Интеграции', exact=True).click()
    expect(page.locator('.integration-item').filter(has_text='Ботанический')).to_contain_text('Подключено · демо')
    page.get_by_role('button', name='Отключить Ботанический', exact=True).click()
    page.get_by_role('dialog').get_by_role('button', name='Отмена', exact=True).click()
    expect(page.locator('.integration-item').filter(has_text='Ботанический')).to_contain_text('Подключено · демо')
    page.get_by_role('button', name='Отключить Ботанический', exact=True).click()
    page.get_by_role('button', name='Отключить источник', exact=True).click()
    expect(page.locator('.integration-item').filter(has_text='Ботанический')).to_contain_text('Не подключён')
    page.get_by_role('button', name='Подключить Самал', exact=True).click()
    page.get_by_role('button', name='Запустить демо-подключение', exact=True).click()
    page.keyboard.press('Escape')
    expect(page.get_by_role('dialog')).to_have_count(0)
    assert not page.evaluate('JSON.parse(localStorage.getItem("romeo-demo-v1-connections")).some(c => c.storeId === "s4")')
    print('PASS: demo connection, progress, refresh, persistence, disconnect and cancellation')

    page.get_by_role('tab', name='Доступы команды', exact=True).click()
    page.get_by_role('button', name='Посмотреть как управляющий', exact=True).click()
    expect(page.get_by_role('heading', name='Ваш магазин в цифрах')).to_be_visible()
    page.get_by_role('button', name='Настройки пространства', exact=True).click()
    expect(page.get_by_label('Название компании', exact=True)).not_to_be_editable()
    expect(page.get_by_role('switch', name='Уведомления о расходах')).to_be_disabled()
    page.get_by_role('tab', name='Интеграции', exact=True).click()
    expect(page.locator('.integration-item')).to_have_count(1)
    expect(page.get_by_role('button', name='Подключить Ботанический', exact=True)).to_have_count(0)
    page.get_by_role('tab', name='Доступы команды', exact=True).click()
    page.get_by_role('button', name='Посмотреть как собственник', exact=True).click()
    print('PASS: role preview and restricted settings')

    page.get_by_role('button', name='Финансы', exact=True).click()
    page.get_by_role('button', name=re.compile('^Заявки на расходы')).click()
    expect(page.get_by_label('Период', exact=True)).to_have_count(0)
    page.get_by_role('button', name=re.compile('Сервис холодильной камеры')).click()
    page.get_by_role('button', name='Отклонить', exact=True).click()
    page.get_by_label('Статус заявки').select_option('rejected')
    expect(page.locator('.requests-table tbody tr')).to_have_count(1)
    expect(page.locator('.requests-table tbody tr')).to_contain_text('Отклонено')
    with page.expect_download():
        page.get_by_role('button', name='Скачать отчёт CSV').click()
    page.get_by_role('button', name='Движение денег', exact=True).click()
    page.get_by_label('Тип операции').select_option('out')
    expect(page.locator('.operation-icon.in')).to_have_count(0)
    page.locator('.operation-name').first.click()
    with page.expect_download():
        page.get_by_role('button', name='Скачать операцию').click()
    page.keyboard.press('Escape')
    page.get_by_role('button', name='Магазины', exact=True).click()
    page.locator('.store-name-button').first.click()
    page.get_by_role('button', name='Задачи магазина', exact=True).click()
    expect(page.locator('.task-card')).not_to_have_count(0)
    page.locator('.kanban-column.done').get_by_role('button', name='Открыть заново').first.click()
    expect(page.locator('.kanban-column.todo')).to_contain_text('Ознакомиться с правилами списания')
    print('PASS: rejection, status filters, expense CSV, operation CSV, store navigation and task reopening')

    nav.get_by_role('button', name=re.compile('^ИИ-помощник')).click()
    page.get_by_role('button', name='Какая выручка за октябрь?', exact=True).click()
    expect(page.locator('.answer-text')).to_contain_text('Выручка:')
    page.get_by_role('button', name='Новый диалог', exact=True).click()
    expect(page.locator('.answer-text')).to_have_count(0)
    nav.get_by_role('button', name='Настройки', exact=True).click()
    page.get_by_role('button', name='Тестовый диалог', exact=True).click()
    expect(page.get_by_role('heading', name=re.compile('Спросите ROMEO'))).to_be_visible()
    print('PASS: new conversation and test-dialog shortcut')

    nav.get_by_role('button', name='Настройки', exact=True).click()
    page.get_by_role('button', name='Сбросить демо', exact=True).click()
    page.get_by_role('button', name='Восстановить демо', exact=True).click()
    expect(page.locator('.workspace-switch')).to_contain_text('Romeo Flowers')
    expect(page.locator('.quick-start')).to_be_visible()
    expect(page.get_by_role('switch', name='Быстрый старт')).to_have_attribute('aria-checked', 'true')
    expect(page.get_by_role('switch', name='Уведомления о расходах')).to_have_attribute('aria-checked', 'true')
    page.evaluate('window.scrollTo(0, 0)')
    page.screenshot(path=str(OUT / 'settings-reference.png'), full_page=True)
    for width in [390, 768, 1024]:
        page.set_viewport_size({'width': width, 'height': 844})
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), f'settings overflow at {width}'
        page.get_by_role('tab', name='Доступы команды', exact=True).click()
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), f'access overflow at {width}'
        page.get_by_role('tab', name='Интеграции', exact=True).click()
        assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), f'integrations overflow at {width}'
        page.get_by_role('tab', name='Общие настройки', exact=True).click()
    page.set_viewport_size({'width': 390, 'height': 844})
    page.screenshot(path=str(OUT / 'settings-mobile.png'), full_page=True)
    expect(page.locator('.global-search')).to_be_visible()
    page.get_by_label('Поиск по системе').fill('Самал')
    page.locator('.search-results').get_by_role('button').click()
    expect(page.get_by_role('dialog')).to_contain_text('Самал')
    page.keyboard.press('Escape')
    assert not errors, errors
    print('PASS: reset, phone/tablet layouts, mobile search and no JavaScript errors')
    browser.close()
