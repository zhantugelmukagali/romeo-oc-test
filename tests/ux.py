"""Navigation persistence, discoverable actions and recovery from mistakes."""
import os
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

URL = os.environ.get('ROMEO_TEST_URL', 'http://127.0.0.1:5173')
OUT = Path(os.environ.get('ROMEO_TEST_ARTIFACTS', '/tmp/romeo-ux-checks'))
OUT.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 1440, 'height': 1000}, reduced_motion='reduce')
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(URL, wait_until='networkidle')
    nav = page.locator('.sidebar')

    def go(name):
        nav.get_by_role('button', name=re.compile('^' + re.escape(name))).click()

    def role(name):
        page.get_by_role('button', name='Сменить роль', exact=True).click()
        page.get_by_role('dialog').get_by_role('button', name=re.compile(name)).click()

    def create(name):
        page.get_by_role('button', name='Создать', exact=True).click()
        page.locator('.create-popover').get_by_role('button', name=re.compile(name)).click()
        return page.get_by_role('dialog')

    page.get_by_label('Магазин', exact=True).select_option('s4')
    page.get_by_label('Период', exact=True).select_option('week')
    go('Финансы')
    page.get_by_role('button', name='Движение денег', exact=True).click()
    expect(page).to_have_url(re.compile(r'#/finance\?store=s4&period=week&tab=cash$'))
    go('Магазины')
    page.go_back()
    expect(page.get_by_label('Поиск операций')).to_be_visible()
    page.go_forward()
    expect(page).to_have_url(re.compile(r'#/stores\?'))
    page.go_back()
    page.reload(wait_until='networkidle')
    expect(page.get_by_label('Магазин', exact=True)).to_have_value('s4')
    expect(page.get_by_label('Период', exact=True)).to_have_value('week')
    expect(page.get_by_label('Поиск операций')).to_be_visible()
    page.get_by_role('button', name='Сбросить фильтры', exact=True).click()
    expect(page.get_by_label('Магазин', exact=True)).to_have_value('all')
    expect(page.get_by_label('Период', exact=True)).to_have_value('month')
    role('Управляющий')
    page.reload(wait_until='networkidle')
    expect(page.get_by_role('heading', name='Ваш магазин в цифрах')).to_be_visible()
    page.goto(URL + '/#/finance?store=s4&period=week&tab=cash', wait_until='networkidle')
    expect(page.get_by_label('Магазин', exact=True)).to_have_value('s1')
    expect(page).to_have_url(re.compile('store=s1'))
    role('Собственник')
    print('PASS: browser history, reload, shareable context and role scope')

    page.get_by_label('Магазин', exact=True).select_option('s1')
    dialog = create('Заявку на расход')
    expect(dialog.get_by_label('Название расхода')).to_be_focused()
    dialog.get_by_label('Название расхода').fill('UX: оборудование')
    page.keyboard.press('Escape')
    expect(dialog.get_by_role('heading', name='Закрыть без сохранения?')).to_be_visible()
    dialog.get_by_role('button', name='Продолжить заполнение').click()
    expect(dialog.get_by_label('Название расхода')).to_have_value('UX: оборудование')
    dialog.get_by_label('Название расхода').fill('   ')
    dialog.get_by_label('Сумма, ₸').fill('12000')
    dialog.get_by_label('Обоснование').fill('Замена оборудования')
    dialog.get_by_role('button', name='Отправить на согласование').click()
    expect(dialog.get_by_role('alert')).to_be_visible()
    dialog.get_by_label('Название расхода').fill('UX: оборудование')
    dialog.get_by_label('Магазин').select_option('s4')
    dialog.get_by_role('button', name='Отправить на согласование').click()
    expect(page.get_by_label('Магазин', exact=True)).to_have_value('s4')
    row = page.locator('.requests-table tbody tr').filter(has_text='UX: оборудование')
    expect(row).to_be_visible()
    row.get_by_role('button', name=re.compile('^UX: оборудование')).click()
    page.get_by_role('button', name='Согласовать расход', exact=True).click()
    expect(row).to_contain_text('Согласовано')
    page.get_by_role('button', name='Отменить действие', exact=True).click()
    expect(row).to_contain_text('На согласовании')
    page.get_by_label('Поиск заявок').fill('несуществующая заявка')
    page.get_by_role('button', name='Показать все заявки').click()
    expect(row).to_be_visible()
    print('PASS: create from anywhere, draft protection, validation, visible result and undo approval')

    dialog = create('Задачу команде')
    dialog.get_by_label('Название задачи').fill('UX: пересчитать остатки')
    dialog.get_by_label('Ожидаемый результат').fill('Сверены все остатки')
    dialog.get_by_label('Магазин').select_option('s1')
    dialog.get_by_role('button', name='Создать задачу', exact=True).click()
    expect(page.get_by_label('Магазин задач', exact=True)).to_have_value('s1')
    card = page.locator('.task-card').filter(has_text='UX: пересчитать остатки')
    expect(card).to_be_visible()
    card.get_by_role('button', name='Взять в работу').click()
    expect(page.locator('.kanban-column.doing')).to_contain_text('UX: пересчитать остатки')
    page.get_by_role('button', name='Отменить действие', exact=True).click()
    expect(page.locator('.kanban-column.todo')).to_contain_text('UX: пересчитать остатки')
    page.get_by_label('Поиск задач').fill('UX: пересчитать')
    expect(page.locator('.task-card')).to_have_count(1)
    go('Финансы')
    page.get_by_label('Поиск по системе').fill('UX: пересчитать')
    page.get_by_label('Поиск по системе').press('Enter')
    expect(page.locator('.task-card')).to_have_count(1)
    expect(page.get_by_label('Поиск задач')).to_have_value('UX: пересчитать остатки')
    print('PASS: task context, undo task status and keyboard global search')

    go('Настройки')
    page.get_by_label('Название компании', exact=True).fill('ROMEO UX draft')
    go('Финансы')
    go('Настройки')
    expect(page.get_by_label('Название компании', exact=True)).to_have_value('ROMEO UX draft')
    page.reload(wait_until='networkidle')
    expect(page.get_by_label('Название компании', exact=True)).to_have_value('ROMEO UX draft')
    expect(page.locator('.workspace-switch')).not_to_contain_text('ROMEO UX draft')
    page.get_by_role('button', name='Сохранить настройки', exact=True).click()
    expect(page.locator('.workspace-switch')).to_contain_text('ROMEO UX draft')
    page.get_by_role('button', name='Сбросить демо', exact=True).click()
    page.get_by_role('button', name='Восстановить демо', exact=True).click()
    page.get_by_label('Название компании', exact=True).fill('Unsaved reset check')
    page.get_by_role('button', name='Сбросить демо', exact=True).click()
    page.get_by_role('button', name='Восстановить демо', exact=True).click()
    expect(page.get_by_label('Название компании', exact=True)).to_have_value('Romeo Flowers')
    print('PASS: settings draft survives navigation and reload, explicit save applies changes')

    # Fresh context gives screenshots without transient toasts or test records.
    clean = browser.new_context(viewport={'width': 1290, 'height': 900}, reduced_motion='reduce')
    desktop = clean.new_page()
    desktop.goto(URL, wait_until='networkidle')
    desktop.screenshot(path=str(OUT / 'overview-desktop.png'), full_page=True)
    desktop.get_by_role('button', name='Настройки пространства', exact=True).click()
    desktop.screenshot(path=str(OUT / 'settings-desktop.png'), full_page=True)
    mobile = clean.new_page()
    mobile.set_viewport_size({'width': 390, 'height': 844})
    mobile.on('pageerror', lambda error: errors.append(str(error)))
    mobile.goto(URL, wait_until='networkidle')
    bottom = mobile.get_by_role('navigation', name='Мобильная навигация')
    expect(bottom).to_be_visible()
    mobile.screenshot(path=str(OUT / 'overview-mobile.png'), full_page=True)
    bottom.get_by_role('link', name='Финансы', exact=True).click()
    mobile.get_by_role('button', name=re.compile('^Заявки на расходы')).click()
    expect(mobile.locator('.requests-table')).to_be_visible()
    assert not mobile.evaluate('document.documentElement.scrollWidth > innerWidth'), 'Mobile page overflows'
    assert mobile.locator('.requests-table').evaluate('(el) => el.scrollWidth <= el.clientWidth'), 'Request cards overflow'
    mobile.screenshot(path=str(OUT / 'requests-mobile.png'), full_page=True)
    mobile.get_by_role('button', name='Создать', exact=True).click()
    mobile.locator('.create-popover').get_by_role('button', name=re.compile('Заявку на расход')).click()
    mobile.get_by_role('dialog').get_by_label('Название расхода').fill('Черновик')
    mobile.get_by_role('button', name='Закрыть окно', exact=True).click()
    mobile.get_by_role('button', name='Не сохранять', exact=True).click()
    expect(mobile.get_by_role('dialog')).to_have_count(0)
    assert not errors, errors
    print('PASS: mobile bottom navigation, readable request cards, discard flow and no JavaScript errors')
    browser.close()
